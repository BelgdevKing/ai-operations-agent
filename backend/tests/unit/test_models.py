# -- Unique constraints -------------------------------------------------------


def unique_column_sets(model: type) -> set[frozenset[str]]:
    table = table_of(model)
    from sqlalchemy import UniqueConstraint

    sets = {
        frozenset(column.name for column in constraint.columns)
        for constraint in table.constraints
        if isinstance(constraint, UniqueConstraint)
    }
    sets |= {
        frozenset(column.name for column in index.columns)
        for index in table.indexes
        if index.unique
    }
    return sets


def test_organization_slug_is_unique() -> None:
    assert frozenset({"slug"}) in unique_column_sets(Organization)


def test_user_email_is_unique() -> None:
    assert frozenset({"email"}) in unique_column_sets(User)


