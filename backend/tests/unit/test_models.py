@pytest.mark.parametrize(
    ("model", "column_name", "target", "ondelete"),
    [
        (OrganizationMember, "user_id", "users", "CASCADE"),
        (OrganizationMember, "organization_id", "organizations", "CASCADE"),
        (AgentTool, "agent_id", "agents", "CASCADE"),
        (AgentTool, "tool_id", "tools", "CASCADE"),
        (Conversation, "agent_id", "agents", "CASCADE"),
        # A person leaving must not erase what was asked and done.
        (Conversation, "user_id", "users", "RESTRICT"),
        (Message, "conversation_id", "conversations", "CASCADE"),
        # The document outlives the account that uploaded it.
        (Document, "uploaded_by", "users", "SET NULL"),
        (WorkflowStep, "workflow_id", "workflows", "CASCADE"),
        (WorkflowRun, "workflow_id", "workflows", "CASCADE"),
        (WorkflowStepRun, "workflow_run_id", "workflow_runs", "CASCADE"),
        (WorkflowStepRun, "workflow_step_id", "workflow_steps", "CASCADE"),
        (Approval, "requested_by", "users", "RESTRICT"),
        (Approval, "approved_by", "users", "SET NULL"),
        (Approval, "tool_id", "tools", "RESTRICT"),
        # The trail survives the account it refers to.
        (AuditEvent, "user_id", "users", "SET NULL"),
    ],
)
def test_foreign_key_targets_and_delete_behaviour(
    model: type, column_name: str, target: str, ondelete: str
) -> None:
    column = table_of(model).c[column_name]
    foreign_key = next(iter(column.foreign_keys))

    assert foreign_key.column.table.name == target
    assert foreign_key.ondelete == ondelete


def test_audit_resource_reference_is_not_a_foreign_key() -> None:
    """The trail spans every table and must outlive the rows it describes."""
    column = table_of(AuditEvent).c.resource_id

    assert isinstance(column.type, PgUUID)
    assert not column.foreign_keys


def test_every_foreign_key_column_is_indexed() -> None:
    """An unindexed foreign key makes both joins and cascading deletes slow."""
    missing: list[str] = []

    for name, table in Base.metadata.tables.items():
        indexed = {next(iter(index.columns)).name for index in table.indexes}
        indexed |= {next(iter(table.primary_key.columns)).name}
        indexed |= {
            next(iter(constraint.columns)).name
            for constraint in table.constraints
            if hasattr(constraint, "columns") and list(constraint.columns)
        }
        for column in table.c:
            if column.foreign_keys and column.name not in indexed:
                missing.append(f"{name}.{column.name}")

    assert not missing, f"unindexed foreign keys: {missing}"


