# -- Tenant scoping -----------------------------------------------------------


@pytest.mark.parametrize("table_name", sorted(TENANT_SCOPED))
def test_tenant_tables_have_a_non_null_indexed_organization_id(table_name: str) -> None:
    table = Base.metadata.tables[table_name]

    assert "organization_id" in table.c, f"{table_name} must carry the tenant id"
    column = table.c.organization_id
    assert isinstance(column.type, PgUUID)
    assert column.nullable is False, "a tenant-owned row must always have an owner"

    targets = {fk.column.table.name for fk in column.foreign_keys}
    assert targets == {"organizations"}

    indexed = any(next(iter(index.columns)).name == "organization_id" for index in table.indexes)
    assert indexed, f"{table_name}.organization_id must lead an index"


@pytest.mark.parametrize("table_name", sorted(NOT_TENANT_SCOPED))
def test_non_tenant_tables_have_no_organization_id(table_name: str) -> None:
    """Documented on purpose: duplicating the column would create a second
    source of truth that could disagree with the first."""
    assert "organization_id" not in Base.metadata.tables[table_name].c


def test_tenant_scoping_covers_every_table() -> None:
    assert TENANT_SCOPED | set(NOT_TENANT_SCOPED) == EXPECTED_TABLES


def test_organization_cascade_removes_tenant_data() -> None:
    for table_name in TENANT_SCOPED:
        column = Base.metadata.tables[table_name].c.organization_id
        fk = next(iter(column.foreign_keys))
        assert fk.ondelete == "CASCADE", table_name


